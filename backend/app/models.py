"""Domain models shared across the API and the pipeline.

These pydantic models are the *only* representation of a card that leaves this
process. Note what is absent: there is no transcript field, no media path, no OCR
text. Those exist only inside a job workspace and are deleted before the card is
persisted.
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone

from pydantic import BaseModel, Field, field_validator


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class CardStatus(str, enum.Enum):
    """Mirrors com.resourcetracker.domain.model.CardStatus on the client."""

    QUEUED = "QUEUED"
    PROCESSING = "PROCESSING"
    PENDING = "PENDING"
    REVIEWED = "REVIEWED"
    SNOOZED = "SNOOZED"
    FAILED = "FAILED"
    DELETED = "DELETED"


class JobStage(str, enum.Enum):
    QUEUED = "QUEUED"
    FETCHING = "FETCHING"
    EXTRACTING = "EXTRACTING"
    OCR = "OCR"
    SUMMARISING = "SUMMARISING"
    DONE = "DONE"
    FAILED = "FAILED"


class KnowledgeCard(BaseModel):
    """The durable output. This is what the phone stores and shows."""

    title: str = Field(min_length=1, max_length=200)
    summary: str = Field(min_length=1, max_length=4000)
    description: str = Field(default="", max_length=400)
    hashtags: list[str] = Field(default_factory=list, max_length=20)
    creator_name: str | None = Field(default=None, max_length=200)
    creator_username: str | None = Field(default=None, max_length=200)
    creator_bio: str | None = Field(default=None, max_length=400)
    thumbnail_url: str | None = Field(default=None, max_length=2048)
    key_insights: list[str] = Field(default_factory=list, max_length=12)
    action_items: list[str] = Field(default_factory=list, max_length=12)
    topics: list[str] = Field(default_factory=list, max_length=8)

    @field_validator("key_insights", "action_items", "topics", "hashtags")
    @classmethod
    def _trim_and_dedupe(cls, values: list[str]) -> list[str]:
        cleaned: list[str] = []
        for value in values:
            text = " ".join(str(value).split()).strip()
            if text and text not in cleaned:
                cleaned.append(text)
        return cleaned


class CardResponse(BaseModel):
    id: str
    reel_url: str
    title: str
    summary: str
    description: str = Field(default="")
    hashtags: list[str] = Field(default_factory=list)
    creator_name: str | None = None
    creator_username: str | None = None
    creator_bio: str | None = None
    key_insights: list[str] = Field(default_factory=list)
    action_items: list[str] = Field(default_factory=list)
    topics: list[str] = Field(default_factory=list)
    status: CardStatus
    created_at: datetime
    reviewed_at: datetime | None = None
    snooze_until_epoch_day: int | None = None
    provider: str | None = None
    thumbnail_url: str | None = None
    last_error: str | None = None


class SubmitReelRequest(BaseModel):
    """POST /v1/reels body.

    client_card_id is generated by the app so the row can be created locally before
    any network round trip. The server honours it, which avoids a re-key dance when
    the job finishes.
    """

    client_card_id: str = Field(min_length=1, max_length=64)
    reel_url: str = Field(min_length=4, max_length=2048)
    note: str | None = Field(default=None, max_length=2000)
    transcript_override: str | None = Field(
        default=None,
        max_length=200_000,
        description=(
            "User-pasted transcript. Used instead of running a provider when the "
            "active provider cannot read this reel. Never persisted."
        ),
    )
    description: str | None = Field(
        default=None,
        max_length=20_000,
        description=(
            "The reel's caption / description, when the client has one. Instagram "
            "sends only a URL through the share sheet, so this is normally filled "
            "from whatever text shared the link, or typed by the user. It is a "
            "first-class input because the public metadata endpoints are not "
            "readable without Meta App Review, so the caption is the only reliable "
            "source of reel text the app has."
        ),
    )
    creator: str | None = Field(
        default=None,
        max_length=200,
        description=(
            "Who posted the reel - a handle or display name. Same reasoning as "
            "`description`: the Instagram reel URL does not contain the account, so "
            "this cannot be derived from it."
        ),
    )

    @field_validator("creator")
    @classmethod
    def _clean_creator(cls, value: str | None) -> str | None:
        if value is None:
            return None
        cleaned = value.strip().lstrip("@").strip()
        return cleaned or None

    @field_validator("reel_url")
    @classmethod
    def _must_be_http(cls, value: str) -> str:
        url = value.strip()
        if not url.lower().startswith(("http://", "https://")):
            raise ValueError("reel_url must be an http(s) URL")
        return url


